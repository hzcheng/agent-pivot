'use strict';

// Posts the `merge-approval` commit status on a PR head after evaluating the
// owner approval comments. Runs from the merge-approval-gate workflow on
// pull_request_target and issue_comment events: the workflow file and this
// script always come from the default branch, and the PR head is only ever
// read as data (round-2 review Blocker 1 — a PR must not approve itself by
// editing the gate). Fail-closed: unexpected errors exit non-zero without
// posting, so a broken gate blocks merges loudly instead of silently opening
// them. The one exception is the advisory impact-report comment: its
// delivery failure is logged and the verdict status is still posted
// (fail-closed covers the verdict, not the review aid).
//
// Harness Simplification PR 4/6: the AI-authored change-impact declaration
// is gone. The gate regenerates the architecture impact report for the exact
// head and publishes it to the job summary ($GITHUB_STEP_SUMMARY) for owner
// review — never as a PR comment, so no notification email per PR; only
// mechanical errors block the status (classification errors such as a
// relaxing change without architecture approval, capability audit gaps,
// report collection failures).

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { evaluateMergeApproval, findArchitectureApprovalComment } = require('./lib/mergeApprovals');
const { collectChangeImpactContext } = require('./lib/changeImpactContext');

const STATUS_CONTEXT = 'merge-approval';

function readEventPayload() {
    const eventPath = process.env.GITHUB_EVENT_PATH;
    if (!eventPath) {
        throw new Error('GITHUB_EVENT_PATH is not set');
    }
    return JSON.parse(fs.readFileSync(eventPath, 'utf8'));
}

function resolvePullRequestNumber(payload) {
    if (payload.pull_request?.number) {
        return payload.pull_request.number;
    }
    // issue_comment events fire for plain issues too; only PRs carry this key.
    if (payload.issue?.pull_request && payload.issue.number) {
        return payload.issue.number;
    }
    return null;
}

async function api(token, method, resource, body) {
    const response = await fetch(`https://api.github.com${resource}`, {
        method,
        headers: {
            Accept: 'application/vnd.github+json',
            Authorization: `Bearer ${token}`,
            'X-GitHub-Api-Version': '2022-11-28',
        },
        body: body ? JSON.stringify(body) : undefined,
    });
    if (!response.ok) {
        throw new Error(`${method} ${resource} failed: ${response.status} ${await response.text()}`);
    }
    return response.json();
}

async function listAllComments(token, repo, prNumber) {
    const comments = [];
    for (let page = 1; page <= 10; page += 1) {
        const batch = await api(
            token,
            'GET',
            `/repos/${repo}/issues/${prNumber}/comments?per_page=100&page=${page}`,
        );
        comments.push(...batch);
        if (batch.length < 100) {
            break;
        }
    }
    return comments;
}

function git(args) {
    return execFileSync('git', args, { encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] }).trim();
}

/** Render the regenerated impact report as the standing comment body. */
function renderImpactReport({ pullRequest, context }) {
    const { classification, report, assignedCapabilities, expectedBehaviors } = context;
    const delta = report.policyDelta || {};
    const lines = [
        `${REPORT_MARKER}`,
        `### Architecture impact report — \`${pullRequest.head.sha.substring(0, 8)}\``,
        `- classification: **${classification}**`,
        `- touched modules: ${Object.keys(report.touchedModules || {}).join(', ') || '(none)'}`,
        `- protected paths touched: ${(report.protectedTouched || []).join(', ') || '(none)'}`,
        `- harness surface touched: ${((report.harnessDelta || {}).touched || []).join(', ') || '(none)'}`,
        `- mayDependOn grown: ${Object.keys(delta.mayDependOnGrown || {}).join(', ') || '(no)'}`,
        `- entrypoints grown: ${Object.keys(delta.entrypointsGrown || {}).join(', ') || '(no)'}`,
        `- invariants changed: ${Object.keys(delta.invariantChanges || {}).join(', ') || '(no)'}`,
        `- invariants removed: ${(delta.invariantsRemoved || []).join(', ') || '(no)'}`,
        `- baseline grown: ${(delta.baselineGrown || []).join(', ') || '(no)'}`,
        `- waivers added: ${(delta.waiversAdded || []).join(', ') || '(no)'}`,
        `- ledger regressions: ${(delta.ledgerRegressions || []).join(', ') || '(no)'}`,
        `- capabilities: ${(assignedCapabilities || []).join(', ') || '(none)'}`,
        `- behaviors: ${(expectedBehaviors || []).join(', ') || '(none)'}`,
        '',
        'Generated by the merge-approval gate from the exact PR head; the PR body carries no machine-checked declaration.',
    ];
    return lines.join('\n');
}

/** Write the report to the job summary (and the log) — never to the PR,
 * so review aids never generate notification email. */
function publishReport(markdown) {
    console.log(markdown);
    const summaryPath = process.env.GITHUB_STEP_SUMMARY;
    if (summaryPath) {
        try {
            fs.appendFileSync(summaryPath, markdown + '\n');
        } catch (error) {
            console.error(`warning: could not write the job summary: ${error instanceof Error ? error.message : String(error)}`);
        }
    }
}

/**
 * Evaluate the exact PR head — without ever executing head code (round-2
 * review Blocker 1). The head tree is materialized as a detached, read-only
 * git worktree used purely as data; the evaluator code itself comes from the
 * default-branch checkout (the workflow runs on pull_request_target).
 */
function evaluateHeadForPullRequest({ pullRequest, prNumber, architectureApproved }) {
    const baseRefName = pullRequest.base?.ref;
    const headSha = pullRequest.head?.sha;
    if (!baseRefName || !headSha) {
        return { errors: ['PR is missing base/head information for the head evaluation'], reportMarkdown: null };
    }
    git(['fetch', 'origin', baseRefName, `pull/${prNumber}/head`]);
    const worktreeDir = path.join(os.tmpdir(), `gate-head-${process.pid}`);
    try {
        git(['worktree', 'add', '--detach', worktreeDir, headSha]);
        const context = collectChangeImpactContext({
            rootDirectory: worktreeDir,
            baseRef: `origin/${baseRefName}`,
            architectureApproved,
        });
        return {
            errors: context.errors,
            reportMarkdown: renderImpactReport({ pullRequest, context }),
        };
    } finally {
        git(['worktree', 'remove', '--force', worktreeDir]);
    }
}

async function main() {
    const token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
    const repo = process.env.GITHUB_REPOSITORY;
    if (!token || !repo) {
        throw new Error('GITHUB_TOKEN and GITHUB_REPOSITORY are required');
    }
    const payload = readEventPayload();
    const prNumber = resolvePullRequestNumber(payload);
    if (!prNumber) {
        console.log('Not a pull request event; nothing to evaluate.');
        return;
    }
    const ownerLogin = repo.split('/')[0];

    const pullRequest = await api(token, 'GET', `/repos/${repo}/pulls/${prNumber}`);
    const headSha = pullRequest.head?.sha;
    if (!headSha) {
        throw new Error(`PR #${prNumber} has no head sha`);
    }

    const comments = await listAllComments(token, repo, prNumber);
    // Round-2 review Blocker 2: approval binds the exact head SHA, never the
    // committer clock — backdating a commit cannot launder a stale approval.
    const verdict = evaluateMergeApproval({
        comments,
        authorLogin: ownerLogin,
        headSha,
    });
    // Harness Simplification: a relaxing/re-partition classification is
    // authorized by the owner's `approve-architecture <full-head-sha>`
    // comment (replacing Architecture Change record machine authorization).
    const architectureApproval = findArchitectureApprovalComment(comments, {
        authorLogin: ownerLogin,
        headSha,
    });

    // The impact report is a read-only review aid: the gate regenerates it
    // from the exact head and publishes it to the job summary — never as a
    // PR comment, so no notification email per PR. Evaluation errors still
    // block (fail-closed); publishing never does.
    const { errors: headErrors, reportMarkdown } = evaluateHeadForPullRequest({
        pullRequest,
        prNumber,
        architectureApproved: Boolean(architectureApproval),
    });
    if (reportMarkdown) {
        publishReport(reportMarkdown);
    }

    const reasons = [];
    if (!verdict.approved) { reasons.push(verdict.reason); }
    reasons.push(...headErrors.slice(0, 3));
    if (headErrors.length > 3) {
        reasons.push(`+${headErrors.length - 3} more head evaluation errors`);
    }
    const status = {
        context: STATUS_CONTEXT,
        state: verdict.approved && headErrors.length === 0 ? 'success' : 'failure',
        description: (reasons.join(' | ') || 'approved by owner comment').slice(0, 140),
        target_url: verdict.commentUrl || payload.comment?.html_url || undefined,
    };
    await api(token, 'POST', `/repos/${repo}/statuses/${headSha}`, status);
    console.log(`${STATUS_CONTEXT}: ${status.state} — ${status.description}`);
    // The verdict lives in the commit status, not this job's exit code: the
    // required check stays red until approval, while the workflow run itself
    // stays green (it computed and posted successfully). If we crash before
    // posting, the missing status still blocks the merge (fail-closed).
}

main().catch(error => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
});
